export function createAppRouter() {
  inventoryOpeningHooks.guard = guardPosOpening;
  catalogStockHooks.overlay = overlayPosStock;
  catalogStockHooks.stamp = posStockStamp;
  const router = createStaffRouter({ authorizeSynctime, authorizeSession: authorizePosStore });
  registerQuoteRoutes(router);
  registerImageFetchRoutes(router);
  registerCustomerRoutes(router);
  registerCatalogRoutes(router);
  registerSapoSyncRoutes(router);
  registerLegacyImageRoutes(router);
  registerSalesRoutes(router);
  registerPosRoutes(router);
  registerPosReturnRoutes(router);
  registerPosOrderFlowRoutes(router);
  registerCashRoutes(router);
  registerPackingRoutes(router);
  registerHoldRoutes(router);
  registerProgressRoutes(router);
  registerPrintingRoutes(router);
  registerSupplierDirectoryRoutes(router);
  registerPurchaseRoutes(router);
  registerPortalRoutes(router);
  registerNotificationRoutes(router);
  registerTaskRoutes(router);
  registerChatRoutes(router);
  registerCustomerHubRoutes(router);
  registerCustomerDuplicateRoutes(router);
  registerCareRoutes(router);
  registerHrRoutes(router, { revenueOf: memberRevenues }); // thưởng KPI DS / thưởng quý cần DS đơn hàng (staff-hub) mà hr không phụ thuộc bán hàng
  registerAdmsRoutes(router);
  registerSynctimeRoutes(router);
  registerStaffHubRoutes(router);
  registerDashboardRoutes(router);
  registerAuditRoutes(router);
  registerPermissionRoutes(router);
  registerApprovalRoutes(router);
  registerPulseRoutes(router);
  registerNavigationCounts(router);
  registerInventoryRoutes(router);
  registerFlowRoutes(router);
  registerCashbookRoutes(router);
  return router;
}
