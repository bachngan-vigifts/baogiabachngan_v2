test('Draft preserves missing costs/payer; explicit zero differs from blank; free logo printing still requires internal cost',()=>{
 const input={type:'B2B',quoteNo:'COST-REQ',vat:8,customer:'Fixture',printing:{},shipping:{},rows:[{name:'A',qty:2,price:100000,printFee:0,printDescription:'In logo',printing:{}}]};
 const doc=cleanQuotation(input) as any;
 assert.equal(doc.shipping.payer,undefined);assert.equal(doc.printing.totalCost,undefined);assert.equal(doc.rows[0].printing.unitPrice,undefined);
 assert.equal(approvalCosts(doc).missingPrinting,true);assert.equal(approvalCosts(doc).missingShippingPayer,true);
 doc.rows[0].costPrice=0;assert.equal(approvalCosts(doc).missingPurchase,true);
 doc.rows[0].costMode='manual';doc.rows[0].printing.unitPrice=0;doc.shipping={payer:'receiver'};
 assert.equal(approvalCosts(doc).missingPurchase,false);assert.equal(approvalCosts(doc).missingPrinting,false);assert.equal(approvalCosts(doc).missingShipping,false);
 doc.rows[0].costPrice=60000;doc.shipping={payer:'sender',cost:25000};
 assert.equal(profit(doc,99999).shippingCost,25000);assert.equal(profit(doc).gross,55000);
 const visible=withoutCosts(doc);assert.equal(visible.shipping.cost,undefined);assert.equal(doc.shipping.cost,25000,'projection never mutates source');
 assert.equal(keepCosts({...visible,shipping:{payer:'sender',cost:1}},doc).shipping.cost,25000);
 assert.equal(keepCosts({...visible,shipping:{payer:'sender',cost:1}},null).shipping.cost,undefined);
});

test('API cannot bypass missing costs, stale review or mismatched lines; delegated approver sees no costs; declared shipping enters profit',async()=>{
 const f=await setup();
 const q=ok(await f.call('/quotes',f.mgr,'POST',{type:'B2B',quoteNo:'COST-GATE',customer:'Fixture costs',vat:8,rows:[{sku:'00123',name:'Ly',qty:2,price:100000,printDescription:'In logo miễn phí',printFee:0}]}),201);
 const o=ok(await f.call('/orders',f.mgr,'POST',{quoteId:q.id}),201),path='/orders/'+o.id+'/status';
 const approve=(extra={})=>f.call(path,f.mgr,'PUT',{status:'confirmed',verified:true,costWarningsReviewed:true,...extra});
 const update=async(change:(d:any)=>void)=>{const v=ok(await f.call('/quotes/'+q.id,f.mgr));change(v.data);return ok(await f.call('/quotes/'+q.id,f.mgr,'PUT',{revision:v.revision,data:v.data}));};
 assert.equal((await approve()).data.code,'PURCHASE_COST_REQUIRED');
 await update(d=>{d.rows[0].costPrice=60000;d.rows[0].costMode='manual';});
 assert.equal((await approve()).data.code,'PRINTING_COST_REQUIRED');
 await update(d=>{d.rows[0].printing={unitPrice:3000};});
 assert.equal((await approve()).data.code,'SHIPPING_PAYER_REQUIRED');
 await update(d=>{d.shipping={payer:'sender'};});
 assert.equal((await approve()).data.code,'SHIPPING_COST_REQUIRED');
 await update(d=>{d.shipping.cost=0;});
 assert.equal((await approve()).data.code,'SHIPPING_COST_REQUIRED');
 const before=ok(await f.call('/orders/'+o.id+'/approval-preflight',f.mgr));
 await update(d=>{d.shipping.cost=25000;});
 assert.equal((await approve({costQuoteRevision:before.quoteRevision})).data.code,'COSTS_CHANGED');
 assert.equal((await f.db.select().from(salesOrders).where(eq(salesOrders.id,o.id)))[0]!.status,'draft');
 const history=(await f.db.select().from(salesLineCostHistory).where(eq(salesLineCostHistory.orderId,o.id))).length;
 const line=(await f.db.select().from(salesOrderLines).where(eq(salesOrderLines.orderId,o.id)))[0]!;
 await f.db.update(salesOrderLines).set({sku:'WRONG'}).where(eq(salesOrderLines.id,line.id));
 assert.equal(ok(await f.call('/orders/'+o.id+'/approval-preflight',f.mgr)).costs.sourceMismatch,true);
 assert.equal((await approve()).data.code,'COST_SOURCE_MISMATCH');
 assert.equal((await f.db.select().from(salesLineCostHistory).where(eq(salesLineCostHistory.orderId,o.id))).length,history,'failed approval rolls back snapshot writes');
 await f.db.update(salesOrderLines).set({sku:line.sku}).where(eq(salesOrderLines.id,line.id));
 await f.db.update(employees).set({canApprove:true}).where(eq(employees.id,'emp'));
 const delegated=ok(await f.call('/orders/'+o.id+'/approval-preflight',f.emp));
 assert.equal(delegated.costs.missingShipping,false);assert.equal(delegated.purchaseCosts,undefined);
 assert.equal((await f.call('/quotes/'+q.id,f.emp)).status,404,'delegation does not grant access to another department quote');
 ok(await f.call(path,f.emp,'PUT',{status:'confirmed',verified:true,costWarningsReviewed:true,costQuoteRevision:delegated.quoteRevision}));
 const p=ok(await f.call('/profit/orders/'+o.id,f.mgr));
 assert.equal(p.shipping,25000);assert.equal(p.gross,49000,'200000 - 120000 - 6000 - 25000');
 const now=new Date().toISOString();
 await f.db.insert(deliveries).values({id:'cost-shipping-delivery',orderId:o.id,deliveryNo:'GH-COST',status:'planned',plannedDate:'2026-11-20',shippingFee:30000,createdBy:'mgr',createdAt:now,updatedAt:now});
 const actual=ok(await f.call('/profit/orders/'+o.id,f.mgr));
 assert.equal(actual.shipping,30000,'actual fee replaces declared cost, never double counts');
 const existing=(await f.db.select().from(salesOrders).where(eq(salesOrders.id,o.id)))[0]!;
 await f.db.insert(salesOrders).values({...existing,id:'no-cost-source',orderNo:'NO-COST-SOURCE',quoteId:null,status:'draft'});
 await f.db.insert(salesOrderLines).values({...line,id:'no-source-line',orderId:'no-cost-source'});
 const missingSource=await f.call('/orders/no-cost-source/status',f.mgr,'PUT',{status:'confirmed',verified:true,costWarningsReviewed:true});
 assert.equal(missingSource.data.code,'COST_SOURCE_REQUIRED');
});
