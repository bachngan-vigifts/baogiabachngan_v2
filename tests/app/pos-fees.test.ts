import { test } from 'node:test';
import assert from 'node:assert/strict';
import { setup } from '../helpers/pos-fixture.ts';
import { customerPayments, salesOrders, salesOrderLines } from '../../src/modules/sales/schema.ts';
import { stockBalances } from '../../src/modules/inventory/schema.ts';
import { posPaymentRequests } from '../../src/modules/sales/pos-schema.ts';

test('POS có phí: bill tạm/QR không ghi thu/xuất, checkout khớp tiền, chống replay đổi phí và chỉ xuất hàng thật', async () => {
  const f = await setup({ viaClaw: true }), shift = await f.open();
  const body = f.cart(shift.id, { feeName: 'Phí gói quà', feeAmount: 5400, feeQuantity: 2, shippingFee: 20000, tendered: 300000, total: 1, tax: 0 });
  const preview = await f.call('/pos/preview', f.emp, 'POST', body);
  assert.equal(preview.status, 200, JSON.stringify(preview.data));
  assert.equal(preview.data.subtotal, 210000); assert.equal(preview.data.tax, 15200); assert.equal(preview.data.total, 225200);
  assert.equal(preview.data.fees.service.tax, 800);
  const qr = await f.call('/pos/qr', f.emp, 'POST', { ...body, key: crypto.randomUUID() });
  assert.equal(qr.status, 200); assert.equal(qr.data.amount, 225200);
  assert.equal((await f.db.select().from(salesOrders)).length, 0);
  assert.equal((await f.db.select().from(customerPayments)).length, 0);
  assert.equal((await f.db.select().from(stockBalances))[0]!.qty, 10);
  const changed = await f.call('/pos/checkout', f.emp, 'POST', { ...body, key: crypto.randomUUID(), method: 'transfer', confirmed: true, paymentRequestId: qr.data.id, shippingFee: 30000 });
  assert.equal(changed.status, 409, 'QR không được dùng khi phí đổi');
  const sale = await f.call('/pos/checkout', f.emp, 'POST', body);
  assert.equal(sale.status, 201, JSON.stringify(sale.data)); assert.equal(sale.data.total, 225200); assert.equal(sale.data.change, 74800);
  assert.equal((await f.db.select().from(customerPayments))[0]!.amount, 225200);
  assert.equal((await f.db.select().from(stockBalances))[0]!.qty, 8);
  assert.equal((await f.db.select().from(salesOrderLines)).length, 1, 'Phí không phải SKU xuất kho');
  assert.equal((await f.call('/pos/checkout', f.emp, 'POST', body)).data.replayed, true);
  assert.equal((await f.call('/pos/checkout', f.emp, 'POST', { ...body, feeAmount: 20000 })).status, 409);
  const detail = (await f.call('/orders/' + sale.data.id, f.mgr)).data;
  assert.equal(detail.order.posFees.shippingFee, 20000);
  assert.deepEqual(detail.lines.map((l:any)=>[l.listUnitPrice,l.discountType,l.discountValue,l.discountAmount,l.qty,l.unitPrice,l.amount]),
    [[108000,'percent',10,21600,2,90000,180000]], 'Order API preserves the original POS price, discount and net price');
  assert.equal(JSON.parse(detail.order.posSnapshot).lines[0].total,194400);

  const report = (await f.call('/cash/shifts/' + shift.id, f.emp)).data;
  assert.equal(report.cash, 225200);
  assert.equal(f.hooks[0]!.body.total, 225200);
  assert.equal(f.hooks[0]!.body.additional_fees.shipping.tax_percent, 0);
  assert.equal(f.hooks[0]!.body.additional_fees.service.tax_amount, 800);
  assert.equal(f.hooks[0]!.body.additional_fees.service.kind, 'other_service');
  assert.equal(f.hooks[0]!.body.additional_fees.service.quantity, 2);
  assert.equal(f.hooks[0]!.body.additional_fees.service.unit_price, 5400);
  for (const input of [{ shippingFee: -1 }, { feeAmount: 10, feeName: '' }, { shippingFee: 1.2 }]) assert.equal((await f.call('/pos/preview', f.emp, 'POST', { ...body, ...input })).status, 400);
});
test('COD kèm phí: chưa thu không vào két, đổi SL giữ phí và cập nhật công nợ/chuyến giao; bảng không VAT đúng tiền', async () => {
  const f = await setup(), shift = await f.open();
  const b = f.cart(shift.id, { fulfillmentMode: 'cod', feeName: 'Phí in', feeAmount: 10800, shippingFee: 20000, delivery: { address: 'Địa chỉ giao' } });
  const noVat = await f.call('/pos/preview', f.emp, 'POST', { ...b, pricePolicyId: 'retail' });
  assert.equal(noVat.data.tax, 0); assert.equal(noVat.data.total, 210800);
  const sale = await f.call('/pos/checkout', f.emp, 'POST', b);
  assert.equal(sale.status, 201, JSON.stringify(sale.data));
  assert.equal((await f.db.select().from(customerPayments)).length, 0);
  assert.equal((await f.call('/cash/shifts/' + shift.id, f.emp)).data.cash, 0);
  assert.equal((await f.db.select().from(stockBalances))[0]!.qty, 10);
  const detail = (await f.call('/orders/' + sale.data.id, f.mgr)).data;
  assert.equal(detail.deliveries[0].codAmount, 225200);
  const amended = await f.call('/orders/' + sale.data.id + '/pos', f.mgr, 'PUT', { revision: detail.order.revision, reason: 'Khách tăng số lượng', lines: detail.lines.map((l: any) => ({ id: l.id, qty: 3, price: 108000, discountType: 'percent', discountValue: 0 })) });
  assert.equal(amended.status, 200, JSON.stringify(amended.data));
  assert.equal(amended.data.total, 354800);
  const after = (await f.call('/orders/' + sale.data.id, f.mgr)).data;
  assert.equal(after.schedules[0].amount, 354800); assert.equal(after.deliveries[0].codAmount, 354800);
  assert.equal(JSON.parse(after.order.posSnapshot).fees.service.amount, 10800);
  assert.equal((await f.db.select().from(posPaymentRequests)).length, 0);
});

test('POS nhiều phí: snapshot/chi tiết/COD giữ từng dòng, server tính tổng, QR và replay chặn đổi một phí', async () => {
  const f = await setup({ viaClaw:true }), shift = await f.open();
  const serviceFees = [{ name: 'Phí in', quantity: 3, unitPrice: 65000 }, { name: 'Gói quà', quantity: 2, unitPrice: 5400 }];
  const body = f.cart(shift.id, { serviceFees, shippingFee:20000, tendered:500000 });
  const preview = await f.call('/pos/preview',f.emp,'POST',body);
  assert.equal(preview.status,200,JSON.stringify(preview.data)); assert.equal(preview.data.total,420200);
  assert.deepEqual(preview.data.fees.services.map((x:any)=>[x.name,x.quantity,x.unitPrice,x.amount]),[['Phí in',3,65000,195000],['Gói quà',2,5400,10800]]);
  const qr = await f.call('/pos/qr',f.emp,'POST',{...body,key:crypto.randomUUID()}); assert.equal(qr.status,200);
  const renamed = [{...serviceFees[0],name:'Đổi tên phí'},serviceFees[1]];
  assert.equal((await f.call('/pos/checkout',f.emp,'POST',{...body,key:crypto.randomUUID(),method:'transfer',confirmed:true,paymentRequestId:qr.data.id,serviceFees:renamed})).status,409);
  const sale = await f.call('/pos/checkout',f.emp,'POST',body); assert.equal(sale.status,201,JSON.stringify(sale.data));
  assert.equal(sale.data.total,420200); assert.equal(sale.data.fees.services.length,2);
  const detail = (await f.call('/orders/'+sale.data.id,f.mgr)).data;
  assert.equal(detail.order.posFees.services.length,2); assert.equal(JSON.parse(detail.order.posSnapshot).fees.services[1].quantity,2);
  assert.equal((await f.call('/pos/checkout',f.emp,'POST',body)).data.replayed,true);
  assert.equal((await f.call('/pos/checkout',f.emp,'POST',{...body,serviceFees:renamed})).status,409);
  assert.equal((await f.db.select().from(customerPayments))[0]!.amount,420200);
  assert.equal((await f.db.select().from(salesOrderLines)).length,1,'phí không tạo dòng hàng trừ tồn');
  assert.equal(f.hooks[0]!.body.additional_fees.service.lines.length,2);
  assert.match(f.hooks[0]!.body.notes,/Phí in: 3 × 65000/);
  const cod = await f.call('/pos/checkout',f.emp,'POST',{...body,key:crypto.randomUUID(),fulfillmentMode:'cod',delivery:{address:'Địa chỉ thử'}});
  assert.equal(cod.status,201,JSON.stringify(cod.data));
  const codDetail = (await f.call('/orders/'+cod.data.id,f.mgr)).data;
  assert.equal(codDetail.deliveries[0].codAmount,420200);
  assert.equal(codDetail.order.posFees.services[0].amount,195000);
});
