import { test } from 'node:test';
import assert from 'node:assert/strict';
import { eq } from 'drizzle-orm';
import { setup } from '../helpers/pos-fixture.ts';
import { posPaymentRequests } from '../../src/modules/sales/pos-schema.ts';
import { salesOrders, customerPayments } from '../../src/modules/sales/schema.ts';
import { stockMoves } from '../../src/modules/inventory/schema.ts';
import { matchesPosQrReference, normalizePosReference, posQrContent, reservedPosOrderNo } from '../../src/modules/sales/domain/pos-qr-reference.ts';
import { orderNoForCheckout } from '../../src/modules/sales/api/pos-number.ts';

test('QR references show the order number, match bank-normalized text exactly and retain legacy UUID QR', () => {
  const request = { id: 'abcdefab-1234-4321-0000-111111111111', cart: JSON.stringify({ reservedOrderNo: 'POS_20261022_100' }) };
  const modern = { ...request, cart: JSON.stringify({ reservedOrderNo: 'POS_100_22102026' }) };
  assert.equal(posQrContent(modern), 'Thanh toán đơn POS_100_22102026');
  assert.ok(matchesPosQrReference(modern, normalizePosReference('Thanh toan don POS 100 22102026')));
  assert.equal(matchesPosQrReference(modern, normalizePosReference('Thanh toan don POS 1000 22102026')), false);
  assert.equal(posQrContent(request), 'Thanh toán đơn POS_20261022_100');
  assert.ok(matchesPosQrReference(request, normalizePosReference('FT12 Thanh toan don POS 20261022 100 GD')));
  assert.equal(matchesPosQrReference(request, normalizePosReference('Thanh toán đơn POS_20261022_1000')), false);
  const legacy = { ...request, cart: '{}' };
  assert.equal(posQrContent(legacy), 'POS abcdefab1234');
  assert.ok(matchesPosQrReference(legacy, normalizePosReference('POS abcdefab1234BANK')));
  assert.equal(reservedPosOrderNo('{oops'), null);
  assert.equal(reservedPosOrderNo('{"reservedOrderNo":"evil"}'), null);
});

test('QR reserves a unique real POS number; cashier concurrency, SePay, replay, expiration and legacy QR remain safe', async () => {
  const f = await setup(), shift = await f.open();
  const bodyA = f.cart(shift.id), bodyB = f.cart(shift.id);
  const [qa, qb] = await Promise.all([f.call('/pos/qr', f.emp, 'POST', { ...bodyA, reservedOrderNo: 'forged' }), f.call('/pos/qr', f.emp, 'POST', bodyB)]);
  assert.equal(qa.status, 200, JSON.stringify(qa.data)); assert.equal(qb.status, 200, JSON.stringify(qb.data));
  assert.match(qa.data.orderNo, /^POS_\d{3,}_\d{8}$/); assert.notEqual(qa.data.orderNo, qb.data.orderNo);
  assert.equal(qa.data.content, 'Thanh toán đơn ' + qa.data.orderNo);
  assert.equal(new URL(qa.data.url).searchParams.get('addInfo'), qa.data.content);
  assert.equal((await f.db.select().from(salesOrders)).length, 0);
  assert.equal((await f.db.select().from(customerPayments)).length, 0);
  assert.equal((await f.db.select().from(stockMoves)).length, 1, 'only opening stock exists');
  assert.equal((await f.call('/pos/qr', f.emp, 'POST', bodyA)).data.id, qa.data.id);
  const cash = await f.call('/pos/checkout', f.emp, 'POST', f.cart(shift.id, { rows: [{ sku: '00123', qty: 1 }] }));
  assert.equal(cash.status, 201, JSON.stringify(cash.data));
  const [cashOrder] = await f.db.select().from(salesOrders).where(eq(salesOrders.id, cash.data.id));
  assert.ok(![qa.data.orderNo, qb.data.orderNo].includes(cashOrder!.orderNo));
  const [reserved] = await f.db.select().from(posPaymentRequests).where(eq(posPaymentRequests.id, qa.data.id));
  assert.equal(await orderNoForCheckout(f.db, '2099-01-01', reserved), qa.data.orderNo, 'payment after midnight retains displayed number');
  const now = new Date().toISOString();
  await f.db.insert(posPaymentRequests).values(Array.from({ length: 205 }, () => ({ id: crypto.randomUUID(), shiftId: shift.id, requestKey: crypto.randomUUID(), cart: '{}', fingerprint: 'other', amount: 1, createdAt: '2099-01-01T00:00:00Z', expiresAt: '2099-01-02T00:00:00Z' })));
  const hook = async (data: object) => { const r = await f.router.handle(new Request('https://trial.test/api/staff/integrations/sepay/pos-payment', { method: 'POST', headers: { authorization: 'Apikey test-sepay-key', 'content-type': 'application/json' }, body: JSON.stringify({ transferType: 'in', transferAmount: qa.data.amount, accountNumber: '123456', code: 'bank-id-01', content: qa.data.content, ...data }) }), f.env); return { status: r.status, data: await r.json() as any }; };
  assert.equal((await hook({ transferAmount: 1 })).status, 409);
  assert.equal((await hook({ accountNumber: 'bad' })).status, 400);
  const paid = await hook({}); assert.equal(paid.status, 200, JSON.stringify(paid.data)); assert.equal(paid.data.paymentRequestId, qa.data.id);
  assert.equal((await hook({})).data.alreadyConfirmed, true);
  const checkout = { ...bodyA, method: 'transfer', confirmed: true, paymentRequestId: qa.data.id };
  const saved = await f.call('/pos/checkout', f.emp, 'POST', checkout); assert.equal(saved.status, 201, JSON.stringify(saved.data));
  const [actual] = await f.db.select().from(salesOrders).where(eq(salesOrders.id, saved.data.id)); assert.equal(actual!.orderNo, qa.data.orderNo);
  assert.equal((await f.call('/pos/checkout', f.emp, 'POST', checkout)).data.id, saved.data.id);
  assert.equal((await f.call('/pos/checkout', f.emp, 'POST', { ...checkout, key: crypto.randomUUID() })).status, 409);
  const abandoned = await f.call('/pos/qr', f.emp, 'POST', f.cart(shift.id)); assert.equal(abandoned.status, 200);
  await f.db.update(posPaymentRequests).set({ expiresAt: '2000-01-01T00:00:00Z' }).where(eq(posPaymentRequests.id, abandoned.data.id));
  const laterCash = await f.call('/pos/checkout', f.emp, 'POST', f.cart(shift.id, { rows: [{ sku: '00123', qty: 1 }] })); assert.equal(laterCash.status, 201);
  const [later] = await f.db.select().from(salesOrders).where(eq(salesOrders.id, laterCash.data.id));
  assert.ok(Number(later!.orderNo.split('_')[1]) > Number(abandoned.data.orderNo.split('_')[1]), 'expired QR number is never recycled');
  const legacyId = 'abcdefab-1234-4321-0000-111111111111';
  await f.db.insert(posPaymentRequests).values({ id: legacyId, shiftId: shift.id, requestKey: crypto.randomUUID(), cart: '{}', fingerprint: 'legacy', amount: qa.data.amount, createdAt: now, expiresAt: '2099-01-01T00:00:00Z' });
  const legacy = await hook({ content: 'POS abcdefab1234' }); assert.equal(legacy.status, 200, JSON.stringify(legacy.data)); assert.equal(legacy.data.paymentRequestId, legacyId);
});
